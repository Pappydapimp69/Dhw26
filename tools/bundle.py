"""Inline events.js + events-db.js into index.html so the page works as a single file.

Run after editing either data file:  python3 tools/bundle.py
"""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "index.html").read_text()
data = "\n".join((root / f).read_text().replace("</script", "<\\/script") for f in ("events.js", "events-db.js"))
block = f"<!-- DATA:BEGIN (generated by tools/bundle.py) -->\n<script>\n{data}\n</script>\n<!-- DATA:END -->"
pat = re.compile(r"<!-- DATA:BEGIN.*?<!-- DATA:END -->", re.S)
if pat.search(html):
    html = pat.sub(lambda m: block, html)
else:
    html = html.replace('<script src="events.js"></script>\n<script src="events-db.js"></script>', block)
(root / "index.html").write_text(html)
print("bundled", len(html), "bytes")
